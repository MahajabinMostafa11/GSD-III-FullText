#!/usr/bin/env python3
"""Split the publication corpus into chronological ingestion batches.

Every record lands in exactly one batch; none is dropped. Batches are cut at
year boundaries, choosing the cut years that keep batch sizes as even as
possible, so each batch covers a continuous span of years. Records with no
publication year go into the last batch.

Each batch file holds the complete records (every original column, plus
`record_key` and `batch`), so the agent never needs to open the full corpus
or read ahead into a later batch.

Usage:
    python3 scripts/make-batches.py "raw sources/publications_gsd_3.csv" --batches 5

Writes, next to the corpus file:
    batches/batch-1.csv ... batch-N.csv
    batches/manifest.csv   (record_key, batch, year, first author, title)
    batches/README.md      (year span and record count per batch)

Requires: pip3 install pandas
"""

import argparse
import hashlib
import sys
from pathlib import Path

import pandas as pd


def clean_id(value):
    if pd.isna(value):
        return None
    text = str(value).strip()
    if text.endswith(".0"):
        text = text[:-2]
    return text or None


def record_key(row):
    """Stable key: PubMed ID, else DOI, else a hash of title + authors."""
    pmid = clean_id(row.get("PubMed ID"))
    if pmid:
        return f"pmid:{pmid}"
    doi = clean_id(row.get("DOI"))
    if doi:
        return f"doi:{doi.lower()}"
    basis = f"{row.get('Title', '')}|{row.get('Authors', '')}".lower()
    return "title:" + hashlib.sha1(basis.encode("utf-8")).hexdigest()[:12]


def first_author(authors):
    if pd.isna(authors):
        return ""
    return str(authors).split(";")[0].strip()


def choose_cuts(year_counts, n_batches):
    """Pick the last year of each batch so cumulative sizes track equal shares."""
    total = sum(year_counts.values())
    years = sorted(year_counts)
    cumulative, running = [], 0
    for y in years:
        running += year_counts[y]
        cumulative.append((y, running))
    cuts = []
    for k in range(1, n_batches):
        target = total * k / n_batches
        candidates = [(abs(c - target), y) for y, c in cumulative
                      if not cuts or y > cuts[-1]]
        cuts.append(min(candidates)[1])
    return cuts


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("corpus", help="path to the corpus CSV")
    parser.add_argument("--batches", type=int, default=5)
    args = parser.parse_args()

    corpus = Path(args.corpus)
    df = pd.read_csv(corpus, encoding="utf-8-sig", dtype=str, keep_default_na=False,
                     na_values=[""])
    df.columns = [c.strip().strip('"') for c in df.columns]

    df["record_key"] = df.apply(record_key, axis=1)
    years = pd.to_numeric(df["Publication Year"], errors="coerce")
    df["_year"] = years
    df["_author"] = df["Authors"].map(first_author)

    dated = df[df["_year"].notna()]
    counts = dated["_year"].astype(int).value_counts().to_dict()
    cuts = choose_cuts(counts, args.batches)

    def batch_of(year):
        if pd.isna(year):
            return args.batches
        for i, cut in enumerate(cuts, start=1):
            if year <= cut:
                return i
        return args.batches

    df["batch"] = df["_year"].map(batch_of)
    df = df.sort_values(["batch", "_year", "_author", "Title"], na_position="last",
                        kind="mergesort")

    out = corpus.parent / "batches"
    out.mkdir(exist_ok=True)
    original_cols = [c for c in df.columns if not c.startswith("_")]

    lines = [
        "# Ingestion batches",
        "",
        f"Generated by `scripts/make-batches.py` from `{corpus.name}`: chronological, "
        f"{args.batches} batches, cut at year boundaries. Records with no year are in the "
        "last batch. Every record is in exactly one batch.",
        "",
        "| Batch | Years | Records | Undated |",
        "|---|---|---|---|",
    ]
    for b in range(1, args.batches + 1):
        part = df[df["batch"] == b]
        part[original_cols].to_csv(out / f"batch-{b}.csv", index=False)
        ys = part["_year"].dropna()
        span = f"{int(ys.min())}–{int(ys.max())}" if len(ys) else "—"
        lines.append(f"| {b} | {span} | {len(part)} | {part['_year'].isna().sum()} |")
    lines.append(f"| **Total** | | **{len(df)}** | |")

    dup = df["record_key"].duplicated(keep=False)
    if dup.any():
        lines += ["", "Records sharing a record key (kept separately; flag as possible duplicates):", ""]
        for key, grp in df[dup].groupby("record_key"):
            lines.append(f"- `{key}`: batches {sorted(set(grp['batch']))}")

    (out / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    df[["record_key", "batch", "Publication Year", "_author", "Title"]].rename(
        columns={"_author": "First Author"}).to_csv(out / "manifest.csv", index=False)

    if len(df) != sum(len(pd.read_csv(out / f"batch-{b}.csv")) for b in range(1, args.batches + 1)):
        sys.exit("ERROR: batch files do not add up to the corpus")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
